#!/usr/bin/env python3
"""Generate reference and agent command index from a built CLI, without API calls."""
import argparse
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile


def collect(binary):
    commands = []
    with tempfile.TemporaryDirectory(prefix="zstack-docs-") as directory:
        env = {k: v for k, v in os.environ.items() if not k.startswith("ZSTACK_")}
        env["ZSTACK_CONFIG"] = str(Path(directory) / "config.yaml")

        def walk(parts):
            result = subprocess.run([binary, *parts, "--help"], env=env, capture_output=True,
                                    text=True, timeout=15, check=True)
            help_text = "\n".join(line.rstrip() for line in result.stdout.splitlines()).strip()
            if "Usage:" not in help_text:
                raise ValueError(f"Missing usage for {parts}")
            section = re.search(r"Available Commands:\n(.*?)(?:\n\n|\Z)", help_text, re.S)
            children = re.findall(r"^  ([a-z0-9-]+)\s", section.group(1), re.M) if section else []
            top = parts[0] if parts else ""
            category = ("discovery" if not parts or top in {"help", "completion", "version"}
                        else "read" if top in {"get", "describe", "wait", "doctor"}
                        else "local-config" if top == "config"
                        else "authentication" if top in {"login", "logout"}
                        else "mutation")
            alias_section = re.search(r"Aliases:\n  ([^\n]+)", help_text)
            aliases = [a.strip() for a in alias_section.group(1).split(",")] if alias_section else []
            commands.append({"aliases": [a for a in aliases if parts and a != parts[-1]], "command": " ".join(["zstack-cli", *parts]), "category": category,
                             "leaf": not children, "help": help_text})
            for child in children:
                walk([*parts, child])
        walk([])
    return commands


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cli", default="./zstack-cli")
    parser.add_argument("--check", action="store_true", help="Fail if generated documents differ")
    args = parser.parse_args()
    binary = shutil.which(args.cli)
    if not binary:
        parser.error("Build the CLI first with make build")
    commands = collect(str(Path(binary).resolve()))
    root = Path(__file__).resolve().parents[1]
    index = {"schemaVersion": 1, "source": "CLI --help", "notes": [
        "Categories are discovery hints, not authorization. Inspect command flags and user scope.",
        "Read commands may renew a saved account session; use session-only credentials for strict read-only runs.",
        "Help and dry-run do not certify server permissions, license, state or successful execution."],
        "commands": commands}
    content = "# CLI command reference\n\nGenerated by `python3 scripts/generate_cli_docs.py --cli ./zstack-cli`. Do not edit manually.\n\n"
    content += "All command paths, aliases, usage, defaults and flags below come from this source tree's CLI help. Examples containing placeholders must be adapted before execution.\n\n"
    content += "See [中文使用指南](../usage-zh.md), [examples](../../examples/README.md), and [agent execution guide](../agents.md).\n\n"
    content += "## Index\n\n" + "\n".join(f"- [{c['command']}](#{c['command'].replace(' ', '-')})" for c in commands) + "\n\n"
    for command in commands:
        content += f"## {command['command']}\n\n```text\n{command['help']}\n```\n\n"
    outputs = {root / "docs/reference/commands.md": content.rstrip() + "\n",
               root / "docs/reference/commands.json": json.dumps(index, ensure_ascii=False, indent=2) + "\n"}
    for path, value in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != value:
                raise SystemExit(f"Out of date: {path.relative_to(root)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(value)
    print(f"{'Checked' if args.check else 'Generated'} {len(commands)} command paths (including groups). No API requests.")


if __name__ == "__main__":
    main()
